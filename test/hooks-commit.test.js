describe('pre-commit-attribution', () => {
  const HOOK = 'pre-commit-attribution';
  const run = (command, cwd = ws.dir) => ws.hook(HOOK, bash(command, cwd));

  test('bloquea la atribución de IA en el mensaje', () => {
    const cases = [
      'git commit -m "feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>"',
      'git commit -m "feat: x\n\nCo-authored-by: GitHub Copilot <copilot@github.com>"',
      'git commit -m "feat: x\n\nClaude-Session: https://claude.ai/code/session_01abc"',
      'git commit -m "feat: x\n\nhttps://claude.ai/code/session_01abc"',
      'git commit -m "feat: x\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)"',
      'git commit -m "feat: x\n\nGenerated by ChatGPT"',
      'git -C svc-api commit -q -m "fix: y\n\nCo-Authored-By: Claude Sonnet <noreply@anthropic.com>"',
      'git add -A && git commit -m "x\n\nCo-Authored-By: Codex <x@openai.com>"',
      "git commit -F - <<'EOF'\nfeat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>\nEOF",
      'git commit -m "$(cat <<\'EOF\'\nfeat: x\n\n🤖 Generated with [Claude Code]\nEOF\n)"',
    ];
    for (const c of cases) {
      const r = run(c);
      assert.equal(r.code, 2, `${c}\n${r.stderr}`);
      assert.match(r.stderr, /atribución de IA/);
    }
  });

  test('bloquea cuando el mensaje viene de un archivo (-F)', () => {
    ws.put('msg-mala.txt', 'feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n');
    assert.equal(run('git commit -F msg-mala.txt').code, 2);
    assert.equal(run('git commit --file=msg-mala.txt').code, 2);
    ws.put('msg-buena.txt', 'feat: x\n');
    assert.equal(run('git commit -F msg-buena.txt').code, 0);
    assert.equal(run('git commit -F no-existe.txt').code, 0);
  });

  test('sigue pasando un mensaje normal y cualquier cosa que no sea un commit', () => {
    const cases = [
      'git commit -m "feat(x): add the session guard"',
      'git commit -m "docs: explain how Claude Code is configured"',
      'git commit -m "chore: remove the Co-Authored-By lines from the template"',
      'git commit -m "feat: x\n\nCo-Authored-By: Maria Perez <maria@example.com>"',
      'git commit -m "feat: x\n\nCo-Authored-By: dependabot[bot] <bot@example.com>"',
      'git log --grep "Claude-Session"',
      'git status',
      'echo "Co-Authored-By: Claude"',
      'git -C svc-api commit -q -m "feat(settings): add services screen"',
      "git commit -F - <<'EOF'\nfeat: x\nEOF",
    ];
    for (const c of cases) assert.equal(run(c).code, 0, c);
  });

  test('la descripción de un PR no es un commit: no se bloquea', () => {
    assert.equal(run('gh pr create --title t --body "🤖 Generated with Claude Code"').code, 0);
    assert.equal(run('gh pr create --body "Co-Authored-By: Claude"').code, 0);
  });

  test('sin commits.forbidAiAttribution no actúa', () => {
    ws.setConfig(baseConfig({ commits: { forbidAiAttribution: false } }));
    assert.equal(run('git commit -m "x\n\nCo-Authored-By: Claude <noreply@anthropic.com>"').code, 0);
  });

  test('fail-open: JSON ilegible, sin config, config rota', () => {
    assert.equal(ws.hook(HOOK, 'nada').code, 0);
    ws.removeConfig();
    const r = run('git commit -m "x\n\nCo-Authored-By: Claude <noreply@anthropic.com>"');
    assert.equal(r.code, 0);
    assert.match(r.stderr, /ai-workspace\.json/);
    ws.setConfig('{ roto');
    assert.equal(run('git commit -m "Claude-Session: x"').code, 0);
  });
});

