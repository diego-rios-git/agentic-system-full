describe('guard-core: el parser de comandos', () => {
  test('splitSegments parte por && || ; | & respetando comillas y redirecciones', () => {
    assert.deepEqual(core.splitSegments('a && b || c; d | e & f'), ['a', 'b', 'c', 'd', 'e', 'f']);
    assert.deepEqual(core.splitSegments('echo "a && b" && npm ci'), ['echo "a && b"', 'npm ci']);
    assert.deepEqual(core.splitSegments("echo 'a; b'; ls"), ["echo 'a; b'", 'ls']);
    assert.deepEqual(core.splitSegments('npm test 2>&1 | tee out'), ['npm test 2>&1', 'tee out']);
    assert.deepEqual(core.splitSegments('cmd &> out.txt'), ['cmd &> out.txt']);
    assert.deepEqual(core.splitSegments('a\nb'), ['a', 'b']);
  });

  test('los cuerpos de heredoc no son comandos', () => {
    assert.deepEqual(core.splitSegments("git commit -F - <<'EOF'\nnpm ci && rm -rf x\nEOF\nls"), ["git commit -F - <<'EOF'", 'ls']);
  });

  test('tokenize quita las comillas y deja las barras invertidas', () => {
    assert.deepEqual(core.tokenize('npm --prefix "C:\\a b\\x" install'), ['npm', '--prefix', 'C:\\a b\\x', 'install']);
    assert.deepEqual(core.tokenize("echo 'a b' c"), ['echo', 'a b', 'c']);
  });

  test('analyze: gestor sin importar el prefijo, y cd encadenado', () => {
    const items = core.analyze('cd sub && FOO=1 npx rimraf x', path.join(path.sep, 'ws'));
    const last = items[items.length - 1];
    assert.equal(last.word, 'npx');
    assert.equal(last.cwd, path.resolve(path.sep, 'ws', 'sub'));
    assert.equal(core.analyze('C:\\tools\\npm.CMD ci', '.')[0].word, 'npm');
    assert.equal(core.analyze('python -m pip install x', '.')[0].word, 'pip');
    assert.equal(core.analyze('sudo -E npm ci', '.')[0].word, 'npm');
  });

  test('analyze entra en bash -c y en cmd /c', () => {
    assert.ok(core.analyze('bash -c "npm ci && ls"', '.').some((i) => i.word === 'npm'));
    assert.ok(core.analyze('cmd /c "rmdir /s /q x"', '.').some((i) => i.word === 'rmdir'));
  });

  test('positionals salta los flags con valor pero no se traga un subcomando', () => {
    assert.deepEqual(core.positionals(['--prefix', 'x', 'install', '--no-audit']), ['install']);
    assert.deepEqual(core.positionals(['-f', 'install']), ['install']);
    assert.deepEqual(core.positionals(['-D', 'add', 'x']), ['add', 'x']);
  });

  test('slash() de la fixture y de los hooks son consistentes', () => {
    assert.equal(slash('a\\b/c'), 'a/b/c');
  });
});
