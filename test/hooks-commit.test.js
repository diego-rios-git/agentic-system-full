describe('pre-commit-gates', () => {
  const HOOK = 'pre-commit-gates';
  const STATE = '.ai-gates-unverified.json';
  const on = () => ws.setConfig(baseConfig({ hooks: { 'pre-commit-gates': { enabled: true } } }));
  const calls = () => (ws.read('.stub-calls') || '').trim().split('\n').filter(Boolean).map((l) => JSON.parse(l));

  beforeEach(() => {
    // Un run-gates de mentira: registra con qué argumentos lo llamaron y sale como se le pida.
    ws.put(
      'scripts/run-gates.js',
      [
        "const fs = require('fs'); const path = require('path');",
        "fs.appendFileSync(path.join(__dirname, '..', '.stub-calls'), JSON.stringify(process.argv.slice(2)) + '\\n');",
        "process.stdout.write(process.env.STUB_OUT || '');",
        "process.stderr.write(process.env.STUB_ERR || '');",
        'process.exit(Number(process.env.STUB_EXIT || 0));',
      ].join('\n'),
    );
    for (const f of ['.stub-calls', STATE, '.ai-gates-log.jsonl']) fs.rmSync(path.join(ws.dir, f), { force: true });
    on();
  });

  const run = (command, cwd, env) => ws.hook(HOOK, bash(command, cwd), { env });

  test('es opcional: sin hooks.pre-commit-gates.enabled no corre nada', () => {
    ws.setConfig(baseConfig());
    assert.equal(run('git commit -m x', ws.dir, { STUB_EXIT: '1' }).code, 0);
    assert.equal(calls().length, 0);
  });

  test('gates limpios: el commit pasa, y se verifica el repositorio que corresponde', () => {
    assert.equal(run('git commit -m x', ws.repo()).code, 0);
    assert.equal(run('git -C svc-web commit -m x', ws.dir).code, 0);
    assert.equal(run('git commit -m x', ws.dir).code, 0);
    assert.equal(run('git commit -m x', ws.slotRepo()).code, 0);
    assert.deepEqual(calls(), [
      ['--repo', 'svc-api'],
      ['--repo', 'svc-web'],
      ['--all'],
      ['--repo', 'svc-api', '--from', 'implementation-1'],
    ]);
  });

  test('con hallazgos (exit 1) bloquea y muestra el resumen', () => {
    const r = run('git add -A && git commit -m x', ws.repo(), { STUB_EXIT: '1', STUB_OUT: '1 hallazgo(s)\n  [R-1] src/a.ts:3 algo' });
    assert.equal(r.code, 2);
    assert.match(r.stderr, /los gates tienen hallazgos/);
    assert.match(r.stderr, /R-1/);
  });

  test('si NO se pudo verificar (exit 2) no pasa en silencio: avisa, y el reintento pasa con advertencia', () => {
    const first = run('git commit -m x', ws.repo(), { STUB_EXIT: '2', STUB_ERR: 'repo sin clonar' });
    assert.equal(first.code, 2);
    assert.match(first.stderr, /NO se pudieron verificar/);
    assert.match(first.stderr, /repo sin clonar/);

    const retry = run('git commit -m x', ws.repo(), { STUB_EXIT: '2' });
    assert.equal(retry.code, 0);
    assert.match(retry.stderr, /sin verificar/i);
  });

  test('el reintento no vale para otro repositorio ni vencido', () => {
    assert.equal(run('git commit -m x', ws.repo(), { STUB_EXIT: '2' }).code, 2);
    assert.equal(run('git -C svc-web commit -m x', ws.dir, { STUB_EXIT: '2' }).code, 2);
    ws.put(STATE, JSON.stringify({ key: '--repo svc-api#1', ts: new Date(Date.now() - 3600_000).toISOString() }));
    assert.equal(run('git commit -m x', ws.repo(), { STUB_EXIT: '2' }).code, 2);
  });

  test('sin scripts/run-gates.js tampoco pasa en silencio', () => {
    // El script propio de la plantilla copiada también se quita: no queda nada que correr.
    fs.rmSync(path.join(ws.dir, 'scripts', 'run-gates.js'));
    const r = run('git commit -m x', ws.repo());
    assert.equal(r.code, 2);
    assert.match(r.stderr, /falta scripts\/run-gates\.js/);
  });

  test('lo que no es un commit no corre los gates', () => {
    for (const c of ['git status', 'git log --oneline', 'git commit-tree x', 'echo "git commit"', 'git push']) {
      assert.equal(run(c, ws.repo(), { STUB_EXIT: '1' }).code, 0, c);
    }
    assert.equal(calls().length, 0);
  });

  test('un commit fuera del workspace no es asunto de este hook', () => {
    assert.equal(run('git commit -m x', path.dirname(ws.dir), { STUB_EXIT: '1' }).code, 0);
  });

  test('fail-open: JSON ilegible, sin config, config rota', () => {
    assert.equal(ws.hook(HOOK, '{').code, 0);
    ws.removeConfig();
    assert.equal(run('git commit -m x', ws.repo(), { STUB_EXIT: '1' }).code, 0);
    ws.setConfig('{ roto');
    assert.equal(run('git commit -m x', ws.repo(), { STUB_EXIT: '1' }).code, 0);
  });
});

