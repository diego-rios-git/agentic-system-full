describe('pre-bash-heredoc', () => {
  const HOOK = 'pre-bash-heredoc';
  const WIN = { AI_HOOK_PLATFORM: 'win32' };
  const on = () => ws.setConfig(baseConfig({ hooks: { 'pre-bash-heredoc': { enabled: true } } }));
  const run = (command, env = WIN) => ws.hook(HOOK, bash(command, ws.dir), { env });

  beforeEach(on);

  test('bloquea un heredoc con barra invertida en el cuerpo (en Windows)', () => {
    const cases = [
      "python - <<'EOF'\ns = s.replace('a\\n', 'b')\nEOF",
      'cat > x.js <<EOF\nconst re = /\\bfoo/;\nEOF\nnode x.js',
      'cat > x.js <<"EOF"\nconst re = /\\d+/;\nEOF',
      "cat <<-EOT\n\tc:\\tmp\n\tEOT",
    ];
    for (const c of cases) {
      const r = run(c);
      assert.equal(r.code, 2, c);
      assert.match(r.stderr, /barra invertida/);
    }
  });

  test('sigue pasando un heredoc sin barras, <<<, printf y el mensaje de commit normal', () => {
    const cases = [
      "cat > a.md <<'EOF'\n# Título\nSin barras.\nEOF",
      "cat > a.md <<'EOF'\nuno\nEOF\necho 'c:\\\\tmp'",
      "printf 'a\\nb\\n' > x.txt",
      'grep -c x <<< "a\\\\b"',
      "git commit -F - <<'EOF'\nfeat(x): add the gate\nEOF",
      'echo hola',
    ];
    for (const c of cases) assert.equal(run(c).code, 0, c);
  });

  test('solo actúa en Windows: en Linux el heredoc con comillas no toca el cuerpo', () => {
    assert.equal(run("python - <<'EOF'\ns.replace('a\\n', 'b')\nEOF", { AI_HOOK_PLATFORM: 'linux' }).code, 0);
  });

  test('es opcional: sin hooks.pre-bash-heredoc.enabled no actúa', () => {
    ws.setConfig(baseConfig());
    assert.equal(run("python - <<'EOF'\ns.replace('a\\n', 'b')\nEOF").code, 0);
  });

  test('fail-open: JSON ilegible, sin config, config rota', () => {
    const bad = "python - <<'EOF'\ns.replace('a\\n', 'b')\nEOF";
    assert.equal(ws.hook(HOOK, 'x', { env: WIN }).code, 0);
    ws.removeConfig();
    assert.equal(run(bad).code, 0);
    ws.setConfig('{ roto');
    assert.equal(run(bad).code, 0);
  });
});

